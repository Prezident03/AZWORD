export function iconPickerHtml(selected = 'folder', inputId = 'folder-icon') {
  return `<div class="icon-picker" id="${inputId}-picker">
    ${FOLDER_ICONS.map(n => `
      <button type="button" class="icon-picker-btn${n === selected ? ' selected' : ''}"
        data-icon="${n}" onclick="selectIcon('${inputId}','${n}')">
        ${icon(n, { size: 22, color: 'var(--purple-light)' })}
      </button>`).join('')}
    <input type="hidden" id="${inputId}" value="${selected}"/>
  </div>`;
}

window.selectIcon = (inputId, name) => {
  const input = document.getElementById(inputId);
  if (input) input.value = name;
  document.querySelectorAll(`#${inputId}-picker .icon-picker-btn`).forEach(btn => {
    btn.classList.toggle('selected', btn.dataset.icon === name);
  });
};